INSERT INTO public.role_permissions (role_id, permission_id)
SELECT role.id, permission.id
FROM role_grants AS grant_row
JOIN public.roles AS role ON role.code = grant_row.role_code
JOIN public.permissions AS permission
  ON permission.code = grant_row.permission_code
 AND permission.is_active
ON CONFLICT (role_id, permission_id) DO NOTHING;

WITH legacy_map (legacy_code, canonical_code) AS (
  VALUES
    ('WAREHOUSE_ADMINISTRATOR', 'HQ_AREA_MANAGER'),
    ('WAREHOUSE_STAFF', 'STOCK_CONTROLLER'),
    ('BRANCH_ADMINISTRATOR', 'BRANCH_REQUESTER'),
