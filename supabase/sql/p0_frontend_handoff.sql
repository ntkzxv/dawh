INSERT INTO public.user_role_assignments (
  user_id,
  role_id,
  valid_from,
  valid_until,
  assigned_at,
  assigned_by
)
SELECT
  assignment.user_id,
  canonical.id,
  assignment.valid_from,
  assignment.valid_until,
  assignment.assigned_at,
  assignment.assigned_by
FROM public.user_role_assignments AS assignment
JOIN public.roles AS legacy ON legacy.id = assignment.role_id
JOIN legacy_map AS mapping ON mapping.legacy_code = legacy.code
JOIN public.roles AS canonical ON canonical.code = mapping.canonical_code
WHERE assignment.revoked_at IS NULL
ON CONFLICT (user_id, role_id) WHERE revoked_at IS NULL DO NOTHING;

WITH legacy_codes (code) AS (
  VALUES
    ('WAREHOUSE_ADMINISTRATOR'),
    ('WAREHOUSE_STAFF'),
    ('BRANCH_ADMINISTRATOR'),
    ('BRANCH_MANAGER'),
    ('BRANCH_STAFF')
)
UPDATE public.user_role_assignments AS assignment
SET
  revoked_at = now(),
  revoke_reason = 'Replaced by canonical P0 role catalog'
FROM public.roles AS role
JOIN legacy_codes ON legacy_codes.code = role.code
WHERE assignment.role_id = role.id
  AND assignment.revoked_at IS NULL;

UPDATE public.roles AS role
SET is_active = false, updated_at = now()
WHERE role.code IN (
  'WAREHOUSE_ADMINISTRATOR', 'WAREHOUSE_STAFF', 'BRANCH_ADMINISTRATOR',
  'BRANCH_MANAGER', 'BRANCH_STAFF', 'DRIVER'
)
AND NOT EXISTS (
  SELECT 1
  FROM public.user_role_assignments AS assignment
  WHERE assignment.role_id = role.id
    AND assignment.revoked_at IS NULL
    AND (assignment.valid_from IS NULL OR assignment.valid_from <= now())
    AND (assignment.valid_until IS NULL OR assignment.valid_until > now())
);

