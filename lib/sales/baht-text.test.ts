import { describe, expect, it } from "vitest";
import { bahtText } from "@/lib/sales/baht-text";

describe("bahtText", () => {
  it.each([
    ["0", "ศูนย์บาทถ้วน"],
    ["1", "หนึ่งบาทถ้วน"],
    ["11", "สิบเอ็ดบาทถ้วน"],
    ["21", "ยี่สิบเอ็ดบาทถ้วน"],
    ["100", "หนึ่งร้อยบาทถ้วน"],
    ["101", "หนึ่งร้อยเอ็ดบาทถ้วน"],
    ["115.44", "หนึ่งร้อยสิบห้าบาทสี่สิบสี่สตางค์"],
    ["1000000", "หนึ่งล้านบาทถ้วน"],
    ["1000001", "หนึ่งล้านเอ็ดบาทถ้วน"],
    ["21000000", "ยี่สิบเอ็ดล้านบาทถ้วน"],
    ["0.50", "ห้าสิบสตางค์"],
  ])("%s", (input, expected) => expect(bahtText(input)).toBe(expected));
});
